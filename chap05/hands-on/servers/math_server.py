"""math_server.py — FastMCP 製の MCP サーバー (stdio transport)

このファイルは「MCP サーバー側の中の人」です。
ハンズオン 5-A では、このサーバーが公開する add / multiply の 2 ツールを、
クライアント (handson_5A_client.py) から MultiServerMCPClient 経由で取得して使います。

----------------------------------------------------------------------
注目してほしいポイント: @mcp.tool() は @tool とほぼ同じ書き味
----------------------------------------------------------------------
第3章では、自作ツールを `@tool` デコレータで定義しました。
MCP サーバーのツールも、`@mcp.tool()` デコレータを関数に付けるだけです。
  - 関数の引数 + 型ヒント         → ツールの入力スキーマになる
  - docstring (関数の説明文)      → ツールの説明 (description) になる
両者の書き味はほとんど同じ、ということを実感してください。
「サーバーの中の人も、誰かがこうやってツールを作っている」だけなのです。

----------------------------------------------------------------------
transport (接続方式) = stdio
----------------------------------------------------------------------
このサーバーは stdio (標準入出力) で通信します。
stdio は「クライアントがこのスクリプトをサブプロセスとして起動し、
標準入力・標準出力でやり取りする」方式です。
そのため、このファイルを手動で `python math_server.py` と実行する必要はありません。
クライアント側が必要なときに自動で起動してくれます。
(手動で実行すると、入力待ちで止まっているように見えます。Ctrl+C で抜けてください)
"""

from mcp.server.fastmcp import FastMCP

# サーバーを 1 つ作る。引数はサーバーの表示名 (任意)。
mcp = FastMCP("Math")


@mcp.tool()
def add(a: int, b: int) -> int:
    """2 つの整数を足し算して、その合計を返す。

    Args:
        a: 足される数
        b: 足す数
    """
    return a + b


@mcp.tool()
def multiply(a: int, b: int) -> int:
    """2 つの整数を掛け算して、その積を返す。

    Args:
        a: 掛けられる数
        b: 掛ける数
    """
    return a * b


if __name__ == "__main__":
    # transport="stdio" で stdio サーバーとして起動する。
    # クライアントがサブプロセスとしてこのスクリプトを立ち上げ、ここが呼ばれる。
    mcp.run(transport="stdio")
