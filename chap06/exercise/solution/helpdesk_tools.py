"""helpdesk_tools.py — 演習 6-B 用の配布ツール (完成版)

研修コース「LangChain による Agentic AI 開発実践」/ 第6章「Middleware と HITL」

============================================================================
このファイルは「配布物」です。演習中に編集する必要はありません (starter / solution 共通)。
ヘルプデスクエージェントが使う 4 つのローカルツールと、その参照データを定義します。

  読み取り系 (副作用なし):
    - search_faq        : 社内 FAQ をキーワード検索する
    - get_system_status : 社内システムの稼働状況を返す

  副作用あり (= 人間の承認が必要なオペレーション):
    - create_ticket     : サポートチケットを起票する (ダミー実装)
    - reset_password    : ユーザーのパスワードをリセットする (ダミー実装)
============================================================================

【この演習でツールが「ローカル @tool」である理由】
  第5章では FAQ を MCP サーバーから調達しましたが、第6章の主題は Middleware と HITL です。
  そこに集中できるよう、MCP サーバーを立てずに済むローカル @tool 実装として同梱しています
  (各章の演習は、それ自体で完結するのが原則です)。

【副作用ツールはなぜ「ダミー実装」なのか】
  create_ticket / reset_password は本来、チケット管理システムや認証基盤を実際に操作する
  「やり直しの効かない」処理です。研修では本物のシステムを叩けないため、ここでは
  print と固定文字列で「実行されたフリ」をするダミーにしています。
  演習の主眼は「実行する前に人間の承認を挟む (HITL)」仕組みであり、
  ツールの中身そのものではありません。
"""

from langchain.tools import tool

# ----------------------------------------------------------------------
# 配布データ: 社内システムの稼働状況 (ダミー)
# ----------------------------------------------------------------------
SYSTEM_STATUS = {
    "勤怠システム": "正常稼働中",
    "経費精算システム": "正常稼働中",
    "メールサーバー": "一部遅延あり (調査中)",
    "VPN": "メンテナンス中 (本日 22:00 まで)",
}

# ----------------------------------------------------------------------
# 配布データ: 社内 FAQ (ダミー)
# ----------------------------------------------------------------------
FAQ_DATA = {
    "VPN": "VPN に接続できない場合は、まず社内ポータルから最新の VPN クライアントを再インストールし、"
           "二要素認証アプリの時刻同期を確認してください。それでも解決しない場合は情報システム部へ。",
    "パスワード": "パスワードを忘れた場合は、社内ポータルの『パスワード再設定』から手続きできます。"
                  "ロックされた場合の解除は、本人確認のうえ情報システム部での対応が必要です。",
    "経費精算": "経費精算は経費精算システムから申請します。領収書は PDF で添付し、月末締め翌月 10 日払いです。",
    "メール": "メールの容量超過時は、添付ファイルの大きい古いメールを削除するか、アーカイブを利用してください。",
}


# ----------------------------------------------------------------------
# 読み取り系ツール (副作用なし) — 承認不要で素通しさせる対象
# ----------------------------------------------------------------------
@tool
def search_faq(keyword: str) -> str:
    """社内 FAQ をキーワードで検索し、よくある質問への回答を返す。

    VPN・パスワード・経費精算・メールなど、社内の手続きややり方に関する
    「どうすればよいか」という問い合わせに使う。稼働状況の確認には使わない。

    Args:
        keyword: 検索キーワード (例: VPN, パスワード, 経費精算)
    """
    hits = [text for key, text in FAQ_DATA.items() if keyword in key or key in keyword]
    if hits:
        return "\n".join(hits)
    return "該当する FAQ が見つかりませんでした。"


@tool
def get_system_status(service: str) -> str:
    """指定された社内システムの現在の稼働状況を取得する。

    システムが「動いているか」「障害が出ていないか」「メンテナンス中か」といった
    稼働状態の問い合わせに使う。

    Args:
        service: 稼働状況を知りたい社内システムの名称 (例: 勤怠システム, VPN)
    """
    status = SYSTEM_STATUS.get(service, "不明 (登録されていないシステムです)")
    return f"{service}の稼働状況: {status}"


# ----------------------------------------------------------------------
# 副作用ありツール (= HITL で承認を要求する対象) — ダミー実装
# ----------------------------------------------------------------------
@tool
def create_ticket(summary: str, priority: str = "medium") -> str:
    """サポートチケットを起票する。

    ユーザーの問題を情報システム部のキューに登録する「書き込み系」の操作。
    実行するとチケット番号が採番され、取り消しには別途オペレーションが必要になるため、
    人間のオペレーターの承認を得てから実行すべきツール。

    Args:
        summary: チケットの概要 (何に困っているか)
        priority: 優先度 (low / medium / high のいずれか)
    """
    # ダミー実装: 本来はチケット管理システムに登録する。ここでは採番されたフリをする。
    ticket_id = "TICKET-10042"
    print(f"  [副作用] create_ticket 実行: {ticket_id} を起票 "
          f"(summary={summary!r}, priority={priority!r})")
    return f"チケット {ticket_id} を起票しました (優先度: {priority})。担当部署が順次対応します。"


@tool
def reset_password(employee_id: str) -> str:
    """指定した社員アカウントのパスワードをリセットする。

    認証基盤を実際に操作する「書き込み系」かつ「やり直しの効かない」高リスク操作。
    本人確認が前提であり、人間のオペレーターの承認を得てから実行すべきツール。

    Args:
        employee_id: パスワードをリセットする対象の社員 ID (例: emp-sato)
    """
    # ダミー実装: 本来は認証基盤を操作する。ここではリセットされたフリをする。
    temp_password = "Temp-9f3kZ!"
    print(f"  [副作用] reset_password 実行: {employee_id} のパスワードを初期化")
    return (
        f"社員 {employee_id} のパスワードをリセットしました。"
        f"仮パスワードは『{temp_password}』です。初回ログイン時に変更してください。"
    )
