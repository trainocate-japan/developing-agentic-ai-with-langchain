"""knowledge_server.py — 社内ナレッジ検索 MCP サーバー (FastMCP / stdio)

【このファイルは「配布物・完成版」です。受講者が編集する必要はありません】

シナリオ:
  情報システム部門が「社内ナレッジ検索 MCP サーバー」を公開しました。
  これまで各エージェントが自前で持っていた FAQ 検索ロジックを、この MCP サーバーに
  一本化します。エージェント側はこのサーバーに接続してツールを「調達」するだけで、
  FAQ 検索が使えるようになります。

  あなた (受講者) が編集するのはクライアント側 (exercise_5B_helpdesk.py) です。
  このサーバーは「情報システム部門が用意してくれた既製品」だと考えてください。

このサーバーが公開する 2 つのツール (Tools):
  - search_faq(keyword)      … 社内 FAQ をキーワード検索する
  - get_document(doc_id)     … ナレッジ文書の本文を ID で取得する

transport = stdio:
  このサーバーは stdio (標準入出力) で通信します。クライアントがこのスクリプトを
  サブプロセスとして自動起動するため、手動で `python knowledge_server.py` と
  実行する必要はありません (実行すると入力待ちで止まって見えます)。

----------------------------------------------------------------------
補足: @mcp.tool() は第3章の @tool とほぼ同じ書き味
----------------------------------------------------------------------
関数の引数 + 型ヒントが入力スキーマに、docstring が説明 (description) になります。
「サーバーの中の人も、こうやってツールを作っている」だけです。
"""

from mcp.server.fastmcp import FastMCP

mcp = FastMCP("InternalKnowledge")


# --- 社内 FAQ データ (VPN / パスワード / 経費精算 / メール) ---
# 情報システム部門が管理している、という想定のナレッジ。
FAQ_DATA = {
    "VPN": "VPN に接続できない場合は、まず社内ポータルから最新の VPN クライアントを再インストールし、"
           "二要素認証アプリの時刻同期を確認してください。それでも解決しない場合は情報システム部へ。",
    "パスワード": "パスワードを忘れた場合は、社内ポータルの『パスワード再設定』から手続きできます。"
                  "ロックされた場合の解除は、本人確認のうえ情報システム部での対応が必要です。",
    "経費精算": "経費精算は経費精算システムから申請します。領収書は PDF で添付し、月末締め翌月 10 日払いです。"
                "申請後は所属長の承認を経て経理部が処理します。",
    "メール": "メールの容量超過時は、添付ファイルの大きい古いメールを削除するか、アーカイブを利用してください。",
}


# --- ナレッジ文書 (FAQ より詳しい手順書。doc_id で引く) ---
DOCUMENTS = {
    "doc-expense": (
        "【経費精算 詳細手順】\n"
        "1. 経費精算システムにログインし、[新規申請] を押す。\n"
        "2. 費目 (交通費・会議費など) を選び、金額と日付を入力する。\n"
        "3. 領収書を PDF で添付する (スマホ撮影の場合は PDF に変換)。\n"
        "4. [申請] を押すと所属長に承認依頼が飛ぶ。\n"
        "5. 承認後、経理部が処理し、月末締め翌月 10 日に給与口座へ振り込まれる。"
    ),
    "doc-vpn": (
        "【VPN 接続 詳細手順】\n"
        "1. 社内ポータルの [ソフトウェア] から最新 VPN クライアントを入手し再インストール。\n"
        "2. 二要素認証アプリの時刻同期を確認 (ずれていると認証に失敗する)。\n"
        "3. それでも繋がらない場合は、情報システム部にエラーコードを添えて連絡。"
    ),
}


@mcp.tool()
def search_faq(keyword: str) -> str:
    """社内 FAQ をキーワードで検索し、よくある質問への回答を返す。

    VPN・パスワード・経費精算・メールなど、社内の手続きややり方に関する
    「どうすればよいか」という問い合わせに使う。稼働状況の確認には使わない。

    Args:
        keyword: 検索キーワード (例: VPN, パスワード, 経費精算)
    """
    hits = [text for key, text in FAQ_DATA.items() if keyword in key or key in keyword]
    if hits:
        return "\n".join(hits)
    return "該当する FAQ が見つかりませんでした。"


@mcp.tool()
def get_document(doc_id: str) -> str:
    """ナレッジ文書 (詳細手順書) を ID で取得して本文を返す。

    FAQ より踏み込んだ手順や詳細を案内したいときに使う。
    利用できる doc_id: doc-expense (経費精算の詳細手順), doc-vpn (VPN 接続の詳細手順)

    Args:
        doc_id: 取得したい文書の ID (例: doc-expense, doc-vpn)
    """
    return DOCUMENTS.get(doc_id, f"文書が見つかりませんでした (doc_id={doc_id})。")


if __name__ == "__main__":
    # stdio サーバーとして起動。クライアントがサブプロセスとして立ち上げる。
    mcp.run(transport="stdio")
