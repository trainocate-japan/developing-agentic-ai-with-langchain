"""weather_agent.py — ハンズオン 7-A の評価対象エージェント (配布・完成版)

ハンズオン 7-A: LangSmith のオフライン評価を一通り動かす
研修コース「Agentic AI 開発実践 - LangChain 版」/ 第7章「エージェントの評価」

============================================================================
このファイルは「配布物」です。ハンズオン中に編集する必要はありません。
オフライン評価で「採点される側」になる、天気エージェントを定義します。

  ツール:
    - get_weather : 都市の天気を返す (ダミー実装)

  公開する変数・関数:
    - build_weather_agent(degraded=False) : 評価対象エージェントを構成して返す
    - MODEL                               : 評価対象のモデル名 ("provider:model")
    - SYSTEM_PROMPT / SYSTEM_PROMPT_DEGRADED : 通常版 / 劣化版のシステムプロンプト
============================================================================

【なぜ天気エージェントが題材なのか】
  オフライン評価の「4 ステップ (Dataset 作成 → evaluator 定義 → Experiment 実行
  → 結果分析)」を学ぶのが目的なので、業務知識に依存しない中立な題材として
  第3〜4章でおなじみの天気エージェントを使います (演習 7-B では業務寄りの
  ヘルプデスクエージェントを評価します)。

【ツールがダミー実装なのはなぜか】
  本物の天気 API を叩くと応答が日々変わり、「評価のたびに結果が揺れる」原因に
  なります。評価対象の挙動を安定させるため、固定文字列を返すダミーにしています。
  評価で見たいのは「模範応答と突き合わせて応答の質を測る方法」であって、
  ツールが返す値そのものではありません。

【なぜ「劣化版プロンプト」が用意されているのか】
  ハンズオンのステップ④で「プロンプト改修がうっかり品質を下げてしまった」状況を
  再現するためです。劣化版で作った Experiment を通常版と比較ビューで並べると、
  スコアが下がったケースが赤くハイライトされます——教科書 7-3 で学んだ
  「回帰検出」を、自分の目で確かめるための仕掛けです。
"""

from langchain.agents import create_agent
from langchain.tools import tool

# 評価対象エージェントのモデル名は変数に集約 ("provider:model" 形式)。
# 研修実施時に最新のモデル名を確認し、適宜差し替えてください。
MODEL = "openai:gpt-5.4"

# 通常版プロンプト。
# 「必ずツールで調べる」「質問の表記どおりの都市名を渡す」を明示しているのは、
# エージェントの経路 (トラジェクトリ) を安定させ、評価結果を読みやすくするためです。
SYSTEM_PROMPT = (
    "あなたは天気アシスタントです。"
    "都市の天気を聞かれたら、必ず get_weather ツールで現在の天気を調べ、"
    "その結果だけをもとに 1〜2 文で簡潔に答えてください。"
    "get_weather の city には、質問に登場した都市名をそのままの表記で渡します。"
)

# 劣化版プロンプト (ステップ④で使用)。
# 「ペルソナを親しみやすくする」という一見もっともらしい改修が、
#   - 応答が長くなる            → conciseness (簡潔性) が劣化
#   - ツールを使わず推測で答える → correctness (正確性) と trajectory (経路) が劣化
# という副作用を生む——現実のプロンプト修正でよく起きる失敗を再現しています。
SYSTEM_PROMPT_DEGRADED = (
    "あなたは親しみやすい天気アシスタントです。"
    "会話が弾むように、天気の話題に加えて、その都市の豆知識やおすすめの過ごし方、"
    "季節の挨拶などをたっぷり盛り込み、最低でも 5 文以上で答えてください。"
    "すぐに答えられそうな質問には、ツールを使わず一般的な知識で答えても構いません。"
)


@tool
def get_weather(city: str) -> str:
    """指定された都市の現在の天気を返す。

    「〇〇の天気は?」「〇〇は何度?」のような、天気・気温を尋ねる問い合わせに使う。

    Args:
        city: 天気を知りたい都市名 (例: 東京, 大阪)
    """
    # ダミー実装: 評価結果を安定させるため固定文字列を返す (教科書 7-2 と同じ)。
    return f"{city} は晴れ、気温は 22 度です。"


def build_weather_agent(degraded: bool = False):
    """天気エージェントを構成して返す。

    Args:
        degraded: True にすると劣化版プロンプト (SYSTEM_PROMPT_DEGRADED) で構成する。
            ハンズオンのステップ④で「プロンプト改修による回帰」を再現するために使う。

    Returns:
        create_agent が返すエージェント (CompiledStateGraph)。
    """
    return create_agent(
        model=MODEL,
        tools=[get_weather],
        system_prompt=SYSTEM_PROMPT_DEGRADED if degraded else SYSTEM_PROMPT,
    )
