"""expense_tools.py — ハンズオン 6-B 用の配布ツール (完成版)

研修コース「Agentic AI 開発実践 - LangChain 版」/ 第6章「Middleware と HITL」

============================================================================
このファイルは「配布物」です。ハンズオン中に編集する必要はありません。
経費精算エージェントが使う 2 つのローカルツールと、その参照データを定義します。
  - get_expense     : 経費申請の状況を照会する (読み取り系。承認不要)
  - transfer_money  : 実際に送金する (書き込み系・やり直しが効かない。要承認)
============================================================================

【なぜこの 2 つなのか — 「止めるべきツール」と「素通しでよいツール」】
  HITL (Human-in-the-Loop) の設計で最初にやることは、手持ちのツールを
  「人間の承認が要るもの」と「要らないもの」に仕分けることです。

    - get_expense    … 何度実行しても状態が変わらない (冪等な照会)。止める必要はない
    - transfer_money … 実行するとお金が動く。取り消しに別の手続きが要る。必ず止める

  この仕分けをそのままコードにしたものが HumanInTheLoopMiddleware の
  interrupt_on です (handson_6B_hitl.py を参照)。

【なぜダミー実装なのか】
  本来の transfer_money は銀行 API や社内の会計システムを叩きます。研修では
  外部システムを用意せずに「副作用がある」という性質だけを再現したいので、
  実行されたことが分かる print を出すだけのダミーにしています。
  承認フローが正しく効いていれば、reject したときにこの print が
  「出ない」ことで、実行されなかったことを目で確認できます。
"""

from langchain.tools import tool

# ----------------------------------------------------------------------
# 配布データ: 経費申請の状況 (ダミー)
# ----------------------------------------------------------------------
# get_expense が参照する。第6章の教科書 6-4 節の例に合わせた最小構成。
EXPENSE_DATA = {
    "山田": {"件数": 3, "未精算額": 5000, "直近の申請": "出張旅費 (交通費)"},
    "佐藤": {"件数": 1, "未精算額": 12000, "直近の申請": "書籍購入費"},
    "鈴木": {"件数": 0, "未精算額": 0, "直近の申請": "なし"},
}


@tool
def get_expense(employee_name: str) -> str:
    """指定した社員の経費申請の状況を照会する。

    未精算の件数・金額・直近の申請内容を返す「読み取り系」の操作。
    何度実行しても状態は変わらないため、人間の承認は不要。

    Args:
        employee_name: 経費申請の状況を知りたい社員の氏名 (例: 山田)
    """
    record = EXPENSE_DATA.get(employee_name)
    if record is None:
        return f"{employee_name}さんの経費申請は見つかりませんでした。"
    return (
        f"{employee_name}さんの経費申請: 未精算 {record['件数']} 件、"
        f"合計 {record['未精算額']} 円 (直近: {record['直近の申請']})"
    )


@tool
def transfer_money(to: str, amount: int) -> str:
    """指定した相手に指定した金額を送金する。

    実際にお金が動く「書き込み系」かつ「やり直しの効かない」高リスク操作。
    誤った宛先・金額で実行してしまうと取り消しに別の手続きが必要になるため、
    人間の承認を得てから実行すべきツール。

    Args:
        to: 送金先の社員の氏名 (例: 山田)
        amount: 送金する金額 (円)
    """
    # ダミー実装: 本来は銀行 API や会計システムを操作する。ここでは送金されたフリをする。
    # この print が出る = 実際に実行された、ということ。
    # reject したときにこの行が出ないことが「止められた」証拠になる。
    print(f"  [副作用] transfer_money 実行: {to}さんへ {amount} 円を送金")
    return f"{to}さんへ {amount} 円を送金しました。処理番号は TRF-20260827-001 です。"
